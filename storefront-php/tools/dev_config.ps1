    "    'APP_ENV' => 'development',", "    'DB_HOST' => '127.0.0.1',", "    'DB_PORT' => '3399',", "    'DB_NAME' => 'pratyangi_php_test',", "    'DB_USER' => 'root',",
    "    'DB_PASS' => $(& $q (Get-ErpConfigValue 'pass')),",
    "    'WEB_ORIGIN' => 'http://127.0.0.1:8100',",
    "    'SMS_MODE' => 'log',",
    "    'ERP_MODE' => 'http',", "    'ERP_BASE_URL' => 'http://127.0.0.1:$ErpPort',",
    "    'ERP_CATALOG_KEY' => $(& $q $catalogueKey),", "    'ERP_ORDER_KEY' => $(& $q $orderKey),",
    "    'ERP_WAREHOUSE' => 'Main Godown',", "    'CATALOG_CACHE_SECONDS' => '10',",
    ']);')
  if ($LogMail) { $i = [array]::IndexOf($lines, "    'SMS_MODE' => 'log',"); $lines = @($lines[0..$i]) + "    'MAIL_MODE' => 'log'," + @($lines[($i + 1)..($lines.Count - 1)]) } # -LogMail: nothing is sent
  Set-Content -LiteralPath $out -Value $lines -Encoding ascii
  & $Php -l $out | Out-Null; if ($LASTEXITCODE -ne 0) { throw 'config.dev.php has a syntax error' }
  $env:PF_CONFIG = $out
  try { $r = & $Php -r "require '$($project.Replace('\','/'))/app/bootstrap.php'; try { `$c = Pratyangi\Config::load(); echo 'settings load ok: erp=', `$c->erpMode, ' mail=', `$c->mailMode, ' sms=', `$c->smsMode, ' catalogue key set=', (`$c->erpApiKey() !== null ? 'yes' : 'no'), ' order key set=', (`$c->erpOrderApiKey() !== null ? 'yes' : 'no'); } catch (Throwable `$e) { echo 'settings error: ', `$e->getMessage(); }" }
  finally { Remove-Item Env:\PF_CONFIG -ErrorAction SilentlyContinue }
  "config.dev.php written (values not shown); $r"
  Remove-Variable catalogueKey, orderKey
  return
}

# -Check: the keys in config.dev.php are the scratch ERP's own, so they match by construction; this proves the running ERP really accepts them.
$base = "http://127.0.0.1:$ErpPort"
function Get-Status([string]$Method, [string]$Path, [string]$Key, [string]$Body = $null) {
  try {
    $args2 = @{ Uri = "$base/$Path"; Method = $Method; UseBasicParsing = $true; TimeoutSec = 15; Headers = @{ Authorization = "Bearer $Key"; Accept = 'application/json' } }
    if ($Body) { $args2.Body = $Body; $args2.ContentType = 'application/json' }
    return [int](Invoke-WebRequest @args2).StatusCode
  } catch { if ($_.Exception.Response) { return [int]$_.Exception.Response.StatusCode } else { return 0 } }
}
if (-not (Test-FlowPort $ErpPort)) { throw "the scratch ERP is not listening on $ErpPort (run tools\start_dev.ps1)" }
$cat = Get-Status 'GET' 'api/catalog_products.php?limit=1' $catalogueKey
$catWithOrderKey = Get-Status 'GET' 'api/catalog_products.php?limit=1' $orderKey
$ord = Get-Status 'POST' 'api/order_create.php' $orderKey '{}'
$ordWithCatKey = Get-Status 'POST' 'api/order_create.php' $catalogueKey '{}'
$yes = { param($s, $bad) if ($s -eq 0) { 'ERP did not answer' } elseif ($bad) { if ($s -in 401, 403) { 'refused, as it should be' } else { "NOT refused (HTTP $s)" } } else { if ($s -in 401, 403) { "REFUSED (HTTP $s)" } elseif ($s -ge 500) { "ERP error (HTTP $s)" } else { "accepted (HTTP $s)" } } }
"ERP_CATALOG_KEY on the catalogue : $(& $yes $cat $false)"
"ERP_ORDER_KEY   on orders        : $(& $yes $ord $false)   (an empty order is refused by the ERP with 400/422, that is fine)"
"order key on the catalogue        : $(& $yes $catWithOrderKey $true)"
"catalogue key on orders           : $(& $yes $ordWithCatKey $true)"
Remove-Variable catalogueKey, orderKey
if ($cat -in 401, 403 -or $ord -in 401, 403) { exit 1 }
