# Writes config.dev.php (git-ignored) for the local dev server and, with -Check, tests the two ERP keys against the scratch ERP. Prints NO key, password or value.
#   tools\dev_config.ps1          writes config.dev.php: your config.local.php with the local test setup laid over it (MySQL 3399, scratch ERP 8095 with ITS keys,
#                                 SMS in log mode; MAIL_MODE comes from config.local.php (real SMTP if it says smtp)). config.local.php itself is never changed.
#   tools\dev_config.ps1 -Check   asks the running scratch ERP: does ERP_CATALOG_KEY open the catalogue, does ERP_ORDER_KEY open orders (and not the other way round)?
param([switch]$Check, [switch]$LogMail)
. 'E:\Testing fashion store\flow-test\scripts\lib.ps1'
$ErrorActionPreference = 'Stop'
$project = Split-Path -Parent $PSScriptRoot
$out = Join-Path $project 'config.dev.php'
if ($MysqlPort -ne 3399) { throw 'refusing: the database port must be 3399' }

# The scratch ERP's own test-only keys (generated by setup-erp-config.ps1). Read here as values, never shown.
$catalogueKey = Get-ErpConfigValue 'catalogue_key'
$orderKey = Get-ErpConfigValue 'order_ingest_key'

if (-not $Check) {
  $git = & git -C $project check-ignore -q config.dev.php 2>$null; if ($LASTEXITCODE -ne 0) { throw 'config.dev.php is not git-ignored; refusing to write it' }
  $q = { param($s) "'" + ([string]$s).Replace('\', '\\').Replace("'", "\'") + "'" }
  $lines = @('<?php', 'declare(strict_types=1);',
    '// Generated by tools/start_dev.ps1 (tools/dev_config.ps1). Git-ignored. Your config.local.php with the local test setup laid over it; delete this file any time.',
